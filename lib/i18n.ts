export type TranslationKey = keyof typeof TRANSLATIONS["es"]

export function translate(
  lang: Language,
  key: TranslationKey,
  vars?: Record<string, string | number>,
): string {
  const dict = TRANSLATIONS[lang] ?? TRANSLATIONS.es
  const fallback = TRANSLATIONS.es
  let str: string = (dict as Record<string, string>)[key] ?? (fallback as Record<string, string>)[key] ?? key
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      str = str.replace(new RegExp(`\\{${k}\\}`, "g"), String(v))
    }
  }
  return str
}

// Convenience helpers that take the dynamic value (not a translation key).
export function dayLabel(lang: Language, day: DayKey, short = false): string {
  const key = (short ? `day.${day}.short` : `day.${day}`) as TranslationKey
  return translate(lang, key)
}

export function difficultyLabel(lang: Language, level: DifficultyLevel): string {
  return translate(lang, `difficulty.${level}` as TranslationKey)
}

export function priorityLabel(lang: Language, priority: ReminderPriority): string {
  return translate(lang, `priority.${priority}` as TranslationKey)
}
